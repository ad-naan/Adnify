// Start: node node_modules/vite/bin/vite.js --config tests/browser/vite.plan.config.mjs
// Set PLAYWRIGHT_MODULE and BROWSER_EXECUTABLE when using an external runtime.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')

;(async () => {
  const browser = await chromium.launch({ headless:true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath:process.env.BROWSER_EXECUTABLE } : {}) })
  const page = await browser.newPage({ viewport:{width:1920,height:1040} })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const checks = []
  const check = (name, condition) => { assert.ok(condition, name); checks.push(name) }
  try {
    await page.goto('http://127.0.0.1:5206/tests/browser/plan-layout.html')
    const draft = page.getByRole('textbox',{name:'需求草稿'})
    await draft.waitFor()
    await draft.evaluate(node => { window.originalComposer = node })
    await page.getByRole('button',{name:'打开历史',exact:true}).click()
    const dialog = page.getByRole('dialog')
    await dialog.waitFor()
    const bounds = await dialog.boundingBox()
    check('history fills the workbench height', bounds.height === 960 && bounds.y === 48)
    const image = dialog.locator('img')
    await image.evaluate(node => node.decode())
    const mascot = await image.boundingBox()
    const footer = await dialog.locator('footer').boundingBox()
    check('empty mascot is fully visible above the footer', mascot.y >= bounds.y && mascot.y+mascot.height < footer.y)
    check('search receives keyboard focus', await dialog.getByRole('textbox').evaluate(node => document.activeElement === node))
    if (process.env.PLAN_LAYOUT_SCREENSHOT) await page.screenshot({ path:process.env.PLAN_LAYOUT_SCREENSHOT })
    await page.keyboard.press('Escape')
    await dialog.waitFor({state:'hidden'})
    check('closing restores focus to history trigger', await page.getByRole('button',{name:'打开历史',exact:true}).evaluate(node => document.activeElement===node))
    check('closing retains the original draft and DOM node', await draft.inputValue()==='保留这段需求和上下文' && await draft.evaluate(node => window.originalComposer===node))
    await page.getByRole('button',{name:'填充记录'}).click()
    await page.getByRole('button',{name:'打开历史',exact:true}).click()
    const search = dialog.getByRole('textbox')
    await search.fill('计划 42')
    check('search filters records', await dialog.getByRole('button',{name:/计划 42/}).count()===1 && await dialog.getByRole('button',{name:/计划 41/}).count()===0)
    await search.fill('找不到的计划')
    check('unmatched search retains a visible empty state', await dialog.getByText('没有匹配的计划',{exact:true}).isVisible())
    await search.fill('计划 42')
    await dialog.getByRole('button',{name:/计划 42/}).click()
    check('history selection calls the existing handler and closes', await page.locator('#result').textContent()==='selected:42' && await dialog.count()===0)
    await page.getByRole('button',{name:'打开历史',exact:true}).click()
    await search.fill('计划 42')
    await dialog.getByRole('button',{name:'删除计划记录'}).click()
    check('deletion waits for explicit confirmation', await page.locator('#result').textContent()==='selected:42')
    await dialog.getByRole('button',{name:'取消',exact:true}).click()
    check('cancel retains the entry', await dialog.getByRole('button',{name:/计划 42/}).count()===1)
    await dialog.getByRole('button',{name:'删除计划记录'}).click()
    await dialog.getByRole('button',{name:'确认',exact:true}).click()
    check('confirmed deletion calls the handler', await page.locator('#result').textContent()==='deleted:42')
    await search.fill('')
    const scrolling = dialog.locator('.custom-scrollbar')
    check('long history scrolls independently', await scrolling.evaluate(node => node.scrollHeight>node.clientHeight))
    check('new plan remains visible for long history', await dialog.getByRole('button',{name:'开始新计划'}).isVisible())
    await page.keyboard.press('Escape')
    await page.getByRole('button',{name:'切换布局'}).click()
    await page.getByRole('button',{name:'打开历史',exact:true}).click()
    const narrow = await dialog.boundingBox()
    check('split layout drawer stays within the chat panel', narrow.width<=480 && narrow.x>=1920*.73 && narrow.height===960)
    await page.setViewportSize({width:1024,height:640})
    const compact = await dialog.boundingBox()
    check('small window drawer fits without clipping', compact.width<=1024*.27+1 && compact.height===560)
    await page.setViewportSize({width:1920,height:1040})
    await dialog.getByRole('button',{name:'开始新计划'}).click()
    check('new plan calls the handler and closes', await page.locator('#result').textContent()==='created' && await dialog.count()===0)
    await page.getByRole('button',{name:'切换布局'}).click()
    await page.getByRole('button',{name:'打开历史',exact:true}).click()
    await page.mouse.click(500,100)
    check('clicking the backdrop closes the drawer', await dialog.count()===0)
    await page.getByRole('button',{name:'需求澄清',exact:true}).click()
    await page.getByRole('button',{name:'仅修改界面'}).click()
    check('clarification selection exposes its state', await page.getByRole('button',{name:'仅修改界面'}).getAttribute('aria-pressed')==='true')
    await page.getByRole('button',{name:'确认选择',exact:true}).click()
    check('clarification forwards the original option id', (await page.locator('#result').textContent()).includes('"ui"'))
    check('no runtime errors', errors.length===0)
    console.log(JSON.stringify({passed:checks.length,checks},null,2))
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode=1 })
